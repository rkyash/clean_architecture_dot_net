namespace MosquitoApi.Domain.Enums;

/// <summary>
/// Enumeration of mosquito size categories
/// </summary>
public enum MosquitoSize
{
    /// <summary>
    /// Small mosquito (less than 4mm)
    /// </summary>
    Small = 1,

    /// <summary>
    /// Medium mosquito (4-6mm)
    /// </summary>
    Medium = 2,

    /// <summary>
    /// Large mosquito (greater than 6mm)
    /// </summary>
    Large = 3
}